#[allow(unused_imports)]
use super::*;

#[cfg(target_arch = "xtensa")]
#[macro_export]
macro_rules! build_runtime_loop_state {
    ($state:expr) => {{
        let BootRuntimeState {
            system,
            tokens,
            #[cfg(feature = "net_http")]
                wifi: _,
            display,
            canvas,
            inputs,
            fan_enable,
            fan_pwm,
            heater_pwm,
            last_heater_duty,
            boot_memory_io_scratch,
            #[cfg(feature = "web_serial")]
            eeprom_snapshot_session,
            memory,
            adc1,
            vin_adc_pin,
            rtd_adc_pin,
            adc_curve,
            controller,
            preview_heater_curve,
            memory_commit_due_ms,
            last_persisted_memory_config,
            last_pd_observation,
            last_pd_status_log_key,
            pd_contract_vin_guard,
            active_thermal_settings,
            manual_pps_state,
            last_fusb302b_power_capabilities,
            calibration_runtime_state,
            thermal_plant_workspace,
            thermal_control_profile_preview,
            heater_power_backend,
            hold_pps_governor,
            heater_controller,
            ui_state,
            current_rtd_fault,
            latest_temp_c,
            latest_temp_i16,
            latest_display_temp_c,
            latest_display_temp_i16,
            latest_rtd_raw_adc_mv,
            latest_rtd_raw_adc_min_mv,
            latest_rtd_raw_adc_max_mv,
            latest_vin_raw_adc_mv,
            latest_vin_mv,
            rtd_pps_transition_guard,
            rtd_control_measurement_guard,
            control_measurement_guarded,
            last_rtd_sample_request_mv,
            last_pid_snapshot,
            cooling_disabled_lock_latched,
            cooling_disabled_lock_armed,
            fan_policy_state,
            heater_enabled_last_cycle,
            last_fan_command,
            last_raw_state,
            fan_command,
            buzzer,
            last_fault_present,
            overtemp_attention_acknowledged,
            attention_pending_after_fault_clear,
            overtemp_forced_fan_active,
            suppress_attention_ack_input,
            suppress_attention_ack_waits_for_event,
            suppress_attention_ack_event_seen,
            suppress_attention_ack_clear_delay_ms,
            suppress_attention_ack_clear_after_ms,
            protection_alarm,
            next_attention_reminder_ms,
            ui_refresh_pending,
            next_ui_refresh_ms,
            suppress_pairing_input_until_released,
        } = $state;
        let BootSystemRuntimeParts {
            reset_reason,
            runtime_mode,
            status_light_started_ms,
            pd_runtime_started_ms,
            pd_contract_ready,
            pd_i2c,
            pd_port,
            eeprom_record_staging,
            #[cfg(feature = "web_serial")]
            usb_serial,
            #[cfg(feature = "web_serial")]
            usb_rx_line,
            #[cfg(feature = "web_serial")]
            usb_tx_buf,
            #[cfg(not(feature = "web_serial"))]
            persistence_log_sink,
        } = system.into();
        let BootMemoryRuntimeParts {
            memory_config,
            memory_sequence,
            eeprom_required,
            eeprom_data_incompatible,
            prepared_layout_recovery_pending,
            persistence_source,
            persistence_record_state,
        } = memory.into();
        drop(boot_memory_io_scratch);
        let BootAdcTokens { .. } = tokens.expect("boot ADC tokens consumed during initialization");
        let adc1 = adc1.expect("ADC driver initialized before runtime");
        let vin_adc_pin = vin_adc_pin.expect("VIN ADC initialized before runtime");
        let rtd_adc_pin = rtd_adc_pin.expect("RTD ADC initialized before runtime");
        let adc_curve = Some(adc_curve.expect("ADC curve initialized before runtime"));
        let runtime_started_ms = pd_runtime_started_ms;
        let last_control_ms = 0;
        let next_control_deadline_ms = HEATER_CONTROL_INTERVAL_MS;
        let next_pd_service_deadline_ms = 0;
        let heater_control_timing = HeaterControlTiming::default();
        let _ = reset_reason;
        let _ = status_light_started_ms;
        let transport = RuntimeTransportState {
            #[cfg(feature = "web_serial")]
            usb_serial,
            #[cfg(feature = "web_serial")]
            usb_rx_line,
            #[cfg(feature = "web_serial")]
            usb_tx_buf,
            #[cfg(feature = "web_serial")]
            eeprom_snapshot_session,
            #[cfg(not(feature = "web_serial"))]
            persistence_log_sink,
        };
        assemble_runtime_loop!(
            runtime_mode,
            display,
            canvas,
            inputs,
            controller,
            pd_i2c,
            pd_port,
            fan_enable,
            fan_pwm,
            heater_pwm,
            adc1,
            vin_adc_pin,
            rtd_adc_pin,
            adc_curve,
            transport,
            eeprom_record_staging,
            memory_config,
            last_persisted_memory_config,
            memory_commit_due_ms,
            memory_sequence,
            eeprom_required,
            eeprom_data_incompatible,
            prepared_layout_recovery_pending,
            persistence_source,
            persistence_record_state,
            preview_heater_curve,
            pd_contract_ready,
            manual_pps_state,
            calibration_runtime_state,
            thermal_plant_workspace,
            thermal_control_profile_preview,
            heater_power_backend,
            hold_pps_governor,
            heater_controller,
            ui_state,
            current_rtd_fault,
            latest_temp_c,
            latest_temp_i16,
            latest_display_temp_c,
            latest_display_temp_i16,
            latest_rtd_raw_adc_mv,
            latest_rtd_raw_adc_min_mv,
            latest_rtd_raw_adc_max_mv,
            latest_vin_raw_adc_mv,
            latest_vin_mv,
            pd_contract_vin_guard,
            rtd_pps_transition_guard,
            rtd_control_measurement_guard,
            control_measurement_guarded,
            last_rtd_sample_request_mv,
            last_pd_observation,
            last_pd_status_log_key,
            last_fusb302b_power_capabilities,
            active_thermal_settings,
            last_pid_snapshot,
            last_heater_duty,
            cooling_disabled_lock_latched,
            cooling_disabled_lock_armed,
            fan_policy_state,
            heater_enabled_last_cycle,
            last_fan_command,
            last_raw_state,
            fan_command,
            buzzer,
            last_fault_present,
            overtemp_attention_acknowledged,
            attention_pending_after_fault_clear,
            overtemp_forced_fan_active,
            suppress_attention_ack_input,
            suppress_attention_ack_waits_for_event,
            suppress_attention_ack_event_seen,
            suppress_attention_ack_clear_delay_ms,
            suppress_attention_ack_clear_after_ms,
            protection_alarm,
            next_attention_reminder_ms,
            status_light_started_ms,
            runtime_started_ms,
            last_control_ms,
            next_control_deadline_ms,
            next_pd_service_deadline_ms,
            heater_control_timing,
            ui_refresh_pending,
            next_ui_refresh_ms,
            suppress_pairing_input_until_released,
        )
    }};
}
